  expect(a11y.violations.map((item) => item.id)).toEqual([]);
  await dialog.locator("[data-quick-transaction-body]").evaluate((el) => { el.scrollTop = 0; });
  await page.screenshot({ path: `${output}/registro.png`, fullPage: false });
  await dialog.getByRole("button", { name: "Guardar gasto", exact: true }).click();
  await expect(dialog).toBeHidden();
