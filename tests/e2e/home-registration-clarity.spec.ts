test("dos pestañas usan el ancho completo, sin columna fantasma", async ({ page }) => {
  await page.goto("/cuentas", { waitUntil: "networkidle" });
  const tabs = page.getByRole("tablist", { name: "Vista de cuentas" });
  const geometry = await tabs.evaluate((el) => ({ track: el.getBoundingClientRect().width, widths: [...el.querySelectorAll('[role="tab"]')].map((tab) => tab.getBoundingClientRect().width) }));
  expect(geometry.widths).toHaveLength(2);
  expect(Math.abs(geometry.widths[0] - geometry.widths[1])).toBeLessThan(1);
  expect(geometry.widths[0] / geometry.track).toBeGreaterThan(.44);
  await tabs.getByRole("tab", { name: /Tarjetas/ }).click();
  const indicator = await tabs.locator("[data-route-tab-indicator]").boundingBox();
  const selected = await tabs.getByRole("tab", { name: /Tarjetas/ }).boundingBox();
  await expect.poll(async () => (await tabs.locator("[data-route-tab-indicator]").boundingBox())!.x).toBeCloseTo(selected!.x, 0);
  expect(indicator!.width).toBeCloseTo(selected!.width, 0);
});

